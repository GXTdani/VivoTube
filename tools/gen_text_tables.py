"""Generates src/core/text_tables.inc, the Unicode tables behind src/core/text.cpp.

The data comes from Python's own unicodedata module, so no download is needed. Re-run it with a
newer Python to pick up a newer Unicode version:

    python -I tools/gen_text_tables.py
"""
import os
import sys
import unicodedata

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src', 'core', 'text_tables.inc')


def ranges(pred, lo=0, hi=0x10FFFF):
    out, start = [], None
    for cp in range(lo, hi + 2):
        ok = cp <= hi and pred(cp)
        if ok and start is None:
            start = cp
        elif not ok and start is not None:
            out.append((start, cp - 1))
            start = None
    return out


def is_mark(cp):
    return unicodedata.category(chr(cp)) in ('Mn', 'Mc', 'Me')


GREEK = set(range(0x391, 0x3AA)) | set(range(0x3B1, 0x3CA)) | {0x3D1, 0x3D5, 0x3F0, 0x3F1, 0x3F4, 0x3F5, 0x2207,
                                                                 0x2202, 0x3DC, 0x3DD}


def styled_target(cp):
    """The plain letter or digit a mathematical / letterlike styled character stands for."""
    try:
        name = unicodedata.name(chr(cp))
    except ValueError:
        return None
    if not any(k in name for k in ('MATHEMATICAL', 'SCRIPT', 'BLACK-LETTER', 'DOUBLE-STRUCK', 'ITALIC', 'BOLD')):
        return None
    nf = unicodedata.normalize('NFKC', chr(cp))
    if len(nf) != 1:
        return None
    t = ord(nf)
    if (t < 0x80 and nf.isalnum()) or t in GREEK:
        return t, 'BOLD' in name
    return None


def fold_runs():
    items = []
    for cp in list(range(0x2100, 0x2150)) + list(range(0x1D400, 0x1D800)):
        r = styled_target(cp)
        if r:
            items.append((cp, r[0], r[1]))
    runs = []
    for cp, t, bold in items:
        if runs and runs[-1][1] + 1 == cp and runs[-1][2] + (cp - runs[-1][0]) == t and runs[-1][3] == bold:
            runs[-1][1] = cp
        else:
            runs.append([cp, cp, t, bold])
    return runs


def main():
    marks = ranges(is_mark, 0, 0x1FFFF) + ranges(is_mark, 0xE0100, 0xE01EF)
    folds = fold_runs()
    lines = ['// Generated by tools/gen_text_tables.py from Unicode %s. Do not edit.' % unicodedata.unidata_version,
             '',
             '// Combining marks (general categories Mn, Mc and Me).',
             'static const uint32_t kMarkRanges[][2] = {']
    row = []
    for a, b in marks:
        row.append('{0x%X, 0x%X}' % (a, b))
        if len(row) == 6:
            lines.append('    ' + ', '.join(row) + ',')
            row = []
    if row:
        lines.append('    ' + ', '.join(row) + ',')
    lines += ['};', '',
              '// Mathematical and letterlike styled letters: first, last, the plain character for first, bold.',
              'struct StyledRun {', '    uint32_t first, last, target;', '    bool bold;', '};',
              'static const StyledRun kStyledRuns[] = {']
    for a, b, t, bold in folds:
        lines.append('    {0x%X, 0x%X, 0x%X, %s},' % (a, b, t, 'true' if bold else 'false'))
    lines += ['};', '']
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines))
    print('%d mark ranges, %d styled runs -> %s' % (len(marks), len(folds), os.path.normpath(OUT)))


if __name__ == '__main__':
    sys.exit(main())
